"""Build data/choices.js from research/choices/*.json: who-can-connect and permission catalogues.
Drops anything without an http(s) source. Run: python3 scripts/build_choices.py"""
import json, glob, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
C = ROOT / 'research' / 'choices'
ok = lambda u: isinstance(u, str) and u.startswith('http')
aud, perms, log = {}, {}, []
for f in sorted(glob.glob(str(C / 'aud*.json'))):
    for a in json.load(open(f)):
        p = a.get('private') or {}
        if not ok(p.get('src')): log.append(f"aud {a.get('id')}: private has no source, skipped"); continue
        aud[a['id']] = {'private': {k: p.get(k) for k in ('works', 'who', 'review', 'text', 'src', 'quote')},
                        'public': {k: (a.get('public') or {}).get(k) for k in ('text', 'src', 'quote')}, 'notes': a.get('notes', '')}
for f in sorted(glob.glob(str(C / 'perm_*.json'))):
    for app, d in json.load(open(f)).items():
        if d.get('varies') is False:
            log.append(f"perm {app}: permissions don't change approval ({(d.get('why') or '')[:70]})"); continue
        opts = []
        for o in d.get('options', []):
            if not ok(o.get('src')): log.append(f"perm {app}.{o.get('k')}: no source, skipped"); continue
            opts.append({k: o.get(k) for k in ('k', 'task', 'scope', 'tier', 'ev', 'src', 'quote', 'note')})
        tiers = {k: {kk: v.get(kk) for kk in ('n', 'effect', 'src', 'quote')} for k, v in (d.get('tiers') or {}).items() if ok(v.get('src'))}
        if opts: perms[app] = {'options': opts, 'tiers': tiers, **({'order': d['order']} if d.get('order') else {}), **({'why': d['why']} if d.get('why') else {})}
(ROOT / 'data' / 'choices.js').write_text('/* Generated by scripts/build_choices.py from research/choices. */\nwindow.CHOICES = ' + json.dumps({'aud': aud, 'perms': perms}, ensure_ascii=False, indent=1) + ';\n')
print(len(aud), 'audience entries,', len(perms), 'permission catalogues'); print('\n'.join(log) or 'no issues')
