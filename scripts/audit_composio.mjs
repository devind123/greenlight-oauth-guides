/* Re-check every guide's Composio facts (auth type, managed OAuth) against docs.composio.dev. */
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(new URL('../data/apps.js', import.meta.url), 'utf8');
const APPS = JSON.parse(src.slice(src.indexOf('['), src.lastIndexOf(']') + 1));
const NAMES = { OAUTH2: 'OAuth 2.0', OAUTH1: 'OAuth 1.0', API_KEY: 'API key', BEARER_TOKEN: 'Bearer token', BASIC: 'Basic auth', S2S_OAUTH2: 'Server-to-server OAuth' };
const out = [];
for (const a of APPS) {
  const url = `https://docs.composio.dev/toolkits/${a.slug}.md`;
  const r = await fetch(url); const md = r.ok ? await r.text() : '';
  const auth = ((md.match(/\*\*Auth:\*\*\s*([^\n]+)/i) || [])[1] || '').trim();
  const managed = ((md.match(/Composio[- ]managed (?:OAuth|auth)[^\n?]*\?\**\s*\**(yes|no|n\/a)/i) || [])[1] || 'unknown').toLowerCase();
  const authNice = auth.split(/[,/|]\s*/).map(x => NAMES[x.trim().toUpperCase()] || x.trim()).join(' or ');
  const ok = managed === a.managed;
  out.push({ id: a.id, status: r.status, ourManaged: a.managed, composioManaged: managed, ourAuth: a.auth, composioAuth: authNice, managedMatch: ok });
  console.log(`${ok ? 'OK  ' : 'DIFF'} ${a.id.padEnd(16)} managed ours=${a.managed} composio=${managed} | auth ours=${a.auth} composio=${authNice}`);
}
console.log(out.filter(x => !x.managedMatch).length, 'managed mismatches');
const map = Object.fromEntries(out.map(x => [x.id, { auths: x.composioAuth.split(' or ').filter(Boolean), managed: x.composioManaged, src: `https://docs.composio.dev/toolkits/${APPS.find(a => a.id === x.id).slug}`, checked: new Date().toISOString().slice(0, 10) }]));
writeFileSync(new URL('../data/composio.js', import.meta.url), '/* Generated by scripts/audit_composio.mjs from docs.composio.dev toolkit pages. */\nwindow.COMPOSIO = ' + JSON.stringify(map) + ';\n');
writeFileSync(new URL('../research/composio_audit.json', import.meta.url), JSON.stringify(out, null, 1));
